import { expect, test } from '@playwright/test';

test.skip(process.env.E2E_SETTINGS !== '1', 'Requires isolated real PostgreSQL and Go API');

test('settings persist, validate and obey permissions on desktop and mobile', async ({ page }, testInfo) => {
  await page.goto('/login');
  await page.getByLabel('用户名').fill(process.env.E2E_ADMIN_USER!);
  await page.getByLabel('密码', { exact: true }).fill(process.env.E2E_ADMIN_PASSWORD!);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page).toHaveURL(/\/admin$/);
  await page.goto('/admin/settings');
  await expect(page.getByRole('heading', { name: '系统设置' })).toBeVisible();
  await expect(page.getByRole('navigation', { name: '管理导航' }).getByRole('link', { name: 'Settings' })).toBeVisible();
  const name = `Isolated ${testInfo.project.name} site`;
  await page.getByLabel('站点名称').fill(name);
  await page.getByLabel('IANA 时区').fill('Asia/Shanghai');
  await page.getByLabel('Logo 同源路径').fill('/logo.svg');
  await page.getByRole('button', { name: '保存更改', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: '系统设置已保存。' })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('站点名称')).toHaveValue(name);
  await expect(page.getByLabel('IANA 时区')).toHaveValue('Asia/Shanghai');
  const read = await page.request.get('/api/v1/admin/settings');
  expect(read.status()).toBe(200);
  const data = (await read.json()).data;
  expect(data.settings['site.name'].value).toBe(name);
  expect(data.settings['localization.timezone'].value).toBe('Asia/Shanghai');
  expect(JSON.stringify(data)).not.toContain('SETTINGS_ENCRYPTION_KEY');
  await page.getByLabel('站点描述').fill('Unsaved change');
  await expect(page.getByRole('button', { name: '撤销未保存更改' })).toBeVisible();
  await page.getByRole('button', { name: '撤销未保存更改' }).click();
  await expect(page.getByLabel('站点描述')).toHaveValue('');
  const csrf = (await (await page.request.get('/api/v1/auth/csrf')).json()).data.csrf_token as string;
  const origin = new URL(page.url()).origin;
  const bad = await page.request.put('/api/v1/admin/settings', { headers: { 'x-csrf-token': csrf, origin }, data: { settings: { 'localization.timezone': 'Unknown/Invalid' } } });
  expect(bad.status()).toBe(422);
  const unknown = await page.request.put('/api/v1/admin/settings', { headers: { 'x-csrf-token': csrf, origin }, data: { settings: { 'server.secret': 'x' } } });
  expect(unknown.status()).toBe(422);
  const noCSRF = await page.request.put('/api/v1/admin/settings', { headers: { origin }, data: { settings: { 'site.name': 'not saved' } } });
  expect(noCSRF.status()).toBe(403);
  await page.route('**/api/v1/admin/settings', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"code":50301,"message":"Service not ready","data":null}' }));
  await page.goto('/admin');
  await page.goto('/admin/settings');
  await expect(page.getByRole('button', { name: '重试' })).toBeVisible();
  await page.unroute('**/api/v1/admin/settings');
  await page.getByRole('button', { name: '重试' }).click();
  await expect(page.getByLabel('站点名称')).toHaveValue(name);
  await page.screenshot({ path: testInfo.outputPath('settings.png'), fullPage: true });
});
