import { expect, test } from '@playwright/test';

test.skip(process.env.E2E_ARTICLES !== '1', 'Requires approved Migration 9 and isolated PostgreSQL');

test('Articles demo CRUD, publication, category guard, audit and RBAC', async ({page,browser},info)=>{
  const username=process.env.E2E_ADMIN_USER!;
  const password=process.env.E2E_ADMIN_PASSWORD!;
  const suffix=`${Date.now()}_${info.project.name}`.replace(/[^a-z0-9_]/gi,'').toLowerCase();
  const slug=`article-${suffix.replaceAll('_','-')}`;
  await page.goto('/login');
  await page.getByLabel('用户名').fill(username);
  await page.getByLabel('密码',{exact:true}).fill(password);
  await page.getByRole('button',{name:'登录',exact:true}).click();
  await expect(page).toHaveURL(/\/admin$/);
  await expect(page.getByRole('navigation',{name:'管理导航'}).getByRole('link',{name:'Articles',exact:true})).toBeVisible();
  const csrf=async()=>((await (await page.request.get('/api/v1/auth/csrf')).json()).data.csrf_token as string);
  const denied=await page.request.post('/api/v1/admin/article-categories',{headers:{Origin:new URL(page.url()).origin,'X-CSRF-Token':'invalid','Content-Type':'application/json'},data:{name:'Blocked',slug:`blocked-${slug}`,description:'',status:'active'}});
  expect(denied.status()).toBe(403);
  await page.goto('/admin/articles/categories');
  const categoryName=`Reports ${suffix}`;
  await page.getByRole('button',{name:'新建分类'}).click();
  await page.getByLabel('名称').fill(categoryName);
  await page.getByLabel('Slug').fill(`Reports-${slug}`);
  await page.getByRole('button',{name:'保存分类'}).click();
  await expect(page.getByRole('status')).toContainText('分类已创建');
  await page.getByRole('button',{name:`编辑 ${categoryName}`,exact:true}).click();
  await page.getByLabel('名称').fill(`${categoryName} updated`);
  await page.getByRole('button',{name:'保存分类'}).click();
  await expect(page.getByText(`${categoryName} updated`,{exact:true})).toBeVisible();
  const category=await page.request.get('/api/v1/admin/article-categories').then(r=>r.json());
  const categoryID=category.data.items.find((item:{slug:string})=>item.slug===`reports-${slug}`)?.id as string;
  expect(categoryID).toBeTruthy();
  await page.goto('/admin/articles/new');
  await page.getByLabel('标题').fill(`Article ${suffix}`);
  await page.getByLabel('Slug').fill(slug.toUpperCase());
  await page.getByLabel('正文').fill('Actual isolated browser test content.');
  await page.getByLabel('分类').selectOption(categoryID);
  await page.getByRole('button',{name:'保存文章'}).click();
  await expect(page).toHaveURL(/\/admin\/articles\/[0-9a-f-]{36}$/);
  const articleID=page.url().split('/').at(-1)!;
  await expect(page.getByText('草稿',{exact:true})).toBeVisible();
  await page.getByLabel('标题').fill(`Edited Article ${suffix}`);
  await page.getByRole('button',{name:'保存文章'}).click();
  await expect(page.getByRole('status')).toContainText('文章已保存');
  await page.reload();
  await expect(page.getByLabel('标题')).toHaveValue(`Edited Article ${suffix}`);
  await page.getByRole('button',{name:'发布',exact:true}).click();
  await expect(page.getByText('已发布',{exact:true})).toBeVisible();
  const published=await page.request.get(`/api/v1/admin/articles/${articleID}`).then(r=>r.json());
  expect(published.data.status).toBe('published');expect(published.data.published_at).toBeTruthy();
  await page.getByRole('button',{name:'取消发布'}).click();
  await expect(page.getByText('草稿',{exact:true})).toBeVisible();
  const draft=await page.request.get(`/api/v1/admin/articles/${articleID}`).then(r=>r.json());
  expect(draft.data.status).toBe('draft');expect(draft.data.published_at).toBeNull();
  const headers=async()=>({Origin:new URL(page.url()).origin,'X-CSRF-Token':await csrf(),'Content-Type':'application/json'});
  const duplicate=await page.request.post('/api/v1/admin/articles',{headers:await headers(),data:{title:'Duplicate',slug:slug.toLowerCase(),summary:'',body:'Content',category_id:null}});
  expect(duplicate.status()).toBe(409);
  const inUse=await page.request.delete(`/api/v1/admin/article-categories/${categoryID}`,{headers:await headers()});
  expect(inUse.status()).toBe(409);
  await page.goto('/admin/articles');
  await page.getByLabel('搜索标题或 Slug').fill(suffix);
  await page.getByRole('button',{name:'搜索'}).click();
  await expect(page.getByText(`Edited Article ${suffix}`)).toBeVisible();
  const viewerName=`viewer_${suffix}`.slice(0,64);
  const viewerPass=`isolated viewer password ${suffix}`;
  const created=await page.request.post('/api/v1/admin/users',{headers:await headers(),data:{username:viewerName,email:`${viewerName}@example.test`,display_name:'Viewer',password:viewerPass}});
  expect(created.status()).toBe(200);
  const context=await browser.newContext();
  try{
    const viewer=await context.newPage();await viewer.goto('/login');
    await viewer.getByLabel('用户名').fill(viewerName);await viewer.getByLabel('密码',{exact:true}).fill(viewerPass);
    await viewer.getByRole('button',{name:'登录',exact:true}).click();await expect(viewer).toHaveURL(/\/admin$/);
    const forbidden=await viewer.request.get('/api/v1/admin/articles');expect(forbidden.status()).toBe(403);
    await viewer.goto('/admin/articles');await expect(viewer.getByRole('alert').filter({hasText:'没有访问此页面的权限'})).toBeVisible();
    await expect(viewer.getByText('当前账号没有已分配的菜单。')).toBeVisible();
  }finally{await context.close()}
  const audits=await page.request.get(`/api/v1/admin/audit-logs?action=article_published`);
  expect(audits.status()).toBe(200);
  await page.screenshot({path:info.outputPath(`articles-${info.project.name}.png`),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true);
  await page.goto(`/admin/articles/${articleID}`);
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'删除草稿'}).click();
  await expect(page).toHaveURL(/\/admin\/articles$/);
  const gone=await page.request.get(`/api/v1/admin/articles/${articleID}`);
  expect(gone.status()).toBe(404);
  await page.goto('/admin/articles/categories');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:`删除 ${categoryName} updated`,exact:true}).click();
  await expect(page.getByText(`${categoryName} updated`,{exact:true})).toHaveCount(0);
});
